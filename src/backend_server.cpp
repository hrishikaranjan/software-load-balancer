// backend_server.cpp - A tiny TCP server that identifies itself in every response.
//
// Usage: backend_server <id> <port> [delay_ms]
// Signals: SIGINT/SIGTERM = graceful exit, SIGUSR1 = toggle simulated failure
//          (closes/re-opens the listening socket, so connections are refused while "down").
#include <atomic>
#include <cerrno>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <netinet/in.h>
#include <poll.h>
#include <string>
#include <sys/socket.h>
#include <thread>
#include <unistd.h>

#include "logger.h"
#include "net_utils.h"
#include "signal_handler.h"

namespace {

std::atomic<int> g_active_handlers{0};

void handle_connection(int fd, int id, int port, int delay_ms) {
    struct Guard { ~Guard() { g_active_handlers--; } } guard;   // RAII counter
    std::string line;
    if (!recv_line(fd, line, 4096, 3000)) { close(fd); return; }  // bare connect (no data): ignore
    while (!line.empty() && (line.back() == '\n' || line.back() == '\r')) line.pop_back();

    if (line == "HEALTH") {                      // health probe from the load balancer
        send_all(fd, "OK\n");
    } else {
        LOG_INFO("Request received: '%s'", line.c_str());
        if (delay_ms > 0) std::this_thread::sleep_for(std::chrono::milliseconds(delay_ms));
        send_all(fd, "Response generated by Backend Server " + std::to_string(id) +
                     " (port " + std::to_string(port) + ") | echo: " + line + "\n");
    }
    close(fd);
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "Usage: %s <id> <port> [delay_ms]\n", argv[0]);
        return 1;
    }
    const int id = std::atoi(argv[1]);
    const int port = std::atoi(argv[2]);
    const int delay_ms = (argc > 3) ? std::atoi(argv[3]) : 0;
    if (id < 1 || port < 1 || port > 65535) { std::fprintf(stderr, "Invalid id/port\n"); return 1; }

    install_signal_handlers();
    logger_init("logs/backend_" + std::to_string(id) + ".log", true);

    int listen_fd = create_listen_socket(port, 128);
    if (listen_fd < 0) {
        LOG_ERROR("Backend Server %d cannot bind port %d: %s", id, port, std::strerror(errno));
        logger_close();
        return 1;
    }
    LOG_INFO("Backend Server %d running on port %d (pid=%d)", id, port, getpid());
    bool simulated_down = false;

    while (!shutdown_requested()) {
        if (consume_usr1()) {                    // toggle simulated failure
            simulated_down = !simulated_down;
            if (simulated_down) {
                close(listen_fd);
                listen_fd = -1;
                LOG_WARN("Backend Server %d: SIMULATED FAILURE (port %d closed)", id, port);
            } else {
                listen_fd = create_listen_socket(port, 128);
                LOG_INFO("Backend Server %d: simulated failure ended, listening again", id);
            }
        }
        if (listen_fd < 0) {                     // down: nothing to accept
            std::this_thread::sleep_for(std::chrono::milliseconds(100));
            continue;
        }
        pollfd p = {listen_fd, POLLIN, 0};
        int pr = poll(&p, 1, 500);
        if (pr <= 0) continue;                   // timeout or EINTR: re-check flags
        int cfd = accept(listen_fd, nullptr, nullptr);
        if (cfd < 0) continue;
        g_active_handlers++;
        std::thread(handle_connection, cfd, id, port, delay_ms).detach();
    }

    LOG_INFO("Backend Server %d shutting down", id);
    if (listen_fd >= 0) close(listen_fd);
    for (int i = 0; i < 50 && g_active_handlers > 0; ++i)       // wait (<=5 s) for handlers
        std::this_thread::sleep_for(std::chrono::milliseconds(100));
    logger_close();
    return 0;
}
